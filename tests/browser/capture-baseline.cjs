const {chromium}=require(process.cwd()+'/node_modules/playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chromium'});
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const evidence='docs/evidence/before/'; const notes=[];
 page.on('pageerror', e=>notes.push({pageerror:e.message}));
 await page.goto('http://localhost:8000/app/');
 await page.locator('.persona-card').first().waitFor();
 await page.screenshot({path:evidence+'login.png',fullPage:true,animations:'disabled'});
 await page.locator('#guest-link').click();
 await page.screenshot({path:evidence+'query-empty.png',fullPage:true,animations:'disabled'});
 await page.locator('#query-input').fill('How do I bake a chocolate cake?');
 const outside=page.waitForResponse(r=>r.url().endsWith('/query')&&r.status()===200);
 await page.locator('#submit-btn').click(); const response=await (await outside).json();
 await page.locator('.result-card').first().waitFor();
 notes.push({case:'outside-domain',docs:[...new Set(response.context.map(d=>d.doc_id))],score:response.context[0].score,tokens:response.total_tokens});
 await page.screenshot({path:evidence+'outside-domain.png',fullPage:true,animations:'disabled'});
 await page.locator('[data-mode="compare"].mode-btn').click();
 await page.locator('#query-input').fill("What is Meridian's ARR growth rate and net revenue retention?");
 const compare=page.waitForResponse(r=>r.url().endsWith('/compare')&&r.status()===200);
 await page.locator('#submit-btn').click(); await compare;
 await page.locator('.compare-col').first().waitFor();
 await page.setViewportSize({width:1024,height:900});
 await page.screenshot({path:evidence+'compare-1024.png',fullPage:true,animations:'disabled'});
 await page.locator('[data-mode="evals"].mode-btn').click();
 await page.locator('.certified-plaque').waitFor();
 await page.screenshot({path:evidence+'metrics.png',fullPage:true,animations:'disabled'});
 await page.locator('#signin-btn').click(); await page.locator('[data-username="patricia"]').click();
 await page.locator('#logout-btn').waitFor();
 await page.locator('[data-mode="compare"].mode-btn').click();
 await page.locator('input[name=role][value=analyst]').check({force:true});
 await page.locator('#query-input').fill("What is Meridian's ARR growth rate?");
 const mismatch=page.waitForResponse(r=>r.url().endsWith('/compare')&&r.status()===200);
 await page.locator('#submit-btn').click(); const mismatched=await(await mismatch).json();
 notes.push({case:'admin-manual-role',selected:'analyst',effective:mismatched.role});
 await page.locator('.compare-col').first().waitFor();
 await page.screenshot({path:evidence+'admin-role-mismatch.png',fullPage:true,animations:'disabled'});
 await page.locator('[data-mode="admin"].mode-btn').click();
 await page.screenshot({path:evidence+'upload.png',fullPage:true,animations:'disabled'});
 await page.locator('#workspace-picker').selectOption('saas-internal');
 await page.locator('[data-username="alex"]').waitFor();
 await page.locator('#guest-link').click();
 await page.screenshot({path:evidence+'saas-empty.png',fullPage:true,animations:'disabled'});
 fs.writeFileSync(evidence+'browser-baseline.json',JSON.stringify(notes,null,2));
 console.log(JSON.stringify(notes,null,2)); await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
