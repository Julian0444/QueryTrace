// Smoke the separately started application. No provider calls and no uploads.
const {chromium,expect}=require('@playwright/test');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch();
 const page=await browser.newPage({baseURL:'http://localhost:8000',viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:8000/app/');
 await expect(page.locator('#welcome-dialog')).toBeVisible();
 await page.screenshot({path:'docs/evidence/after/final-welcome.png',animations:'disabled'});
 await page.locator('#tour-start').click();
 await page.screenshot({path:'docs/evidence/after/final-guide.png',animations:'disabled'});
 await page.locator('#tour-close').click();
 await page.locator('#query-input').fill("What is Meridian's ARR growth rate and net revenue retention?");
 const queryEvent=page.waitForResponse(r=>r.url().endsWith('/query'));
 await page.locator('#submit-btn').click();const query=await(await queryEvent).json();
 expect(query.context.length).toBeGreaterThan(0);
 await expect(page.locator('#executed-query')).toContainText(query.query);
 await page.locator('#executed-query').evaluate(el=>el.scrollIntoView({block:'start'}));
 await page.screenshot({path:'docs/evidence/after/final-query.png',animations:'disabled'});
 await page.locator('.trace-toggle').click();
 await page.locator('.trace-panel').evaluate(el=>el.scrollIntoView({block:'start'}));
 await page.screenshot({path:'docs/evidence/after/final-trace.png',animations:'disabled'});
 await page.locator('.mode-btn[data-mode="compare"]').click();
 const comparisonEvent=page.waitForResponse(r=>r.url().endsWith('/compare'));
 await page.locator('#submit-btn').click();const comparison=await(await comparisonEvent).json();
 expect(comparison.role).toBe('analyst');
 await expect(page.locator('.compare-col')).toHaveCount(3);
 await page.locator('#compare-banner').evaluate(el=>el.scrollIntoView({block:'start'}));
 await page.screenshot({path:'docs/evidence/after/final-comparison.png',animations:'disabled'});
 await page.locator('.mode-btn[data-mode="documents"]').click();
 await expect(page.locator('#documents-section')).toContainText('Meridian');
 await page.screenshot({path:'docs/evidence/after/final-documents.png',animations:'disabled'});
 await page.locator('.mode-btn[data-mode="evals"]').click();
 await expect(page.locator('#evals-content')).toContainText('12 / 12');
 await page.screenshot({path:'docs/evidence/after/final-evaluations.png',animations:'disabled'});
 await page.locator('#workspace-picker').selectOption('saas-internal');
 await expect(page.locator('#identity-context')).toContainText('Employee');
 await page.locator('#query-input').fill('What is the current on-call escalation process and database failover procedure?');
 const saasEvent=page.waitForResponse(r=>r.url().endsWith('/query'));
 await page.locator('#submit-btn').click();const saas=await(await saasEvent).json();
 expect(saas.execution.workspace).toBe('saas-internal');expect(saas.context.length).toBeGreaterThan(0);
 expect((await page.request.get('/__test/state')).status()).toBe(404);
 const health=await(await page.request.get('/health')).json();expect(health.ask_enabled).toBe(false);
 expect(errors).toEqual([]);
 fs.writeFileSync('docs/evidence/after/production-smoke.json',JSON.stringify({health,query,comparison,saas,page_errors:errors,test_control_routes_exposed:false},null,2));
 await browser.close();
 console.log('Production app smoke passed: both real corpora, Query, Compare, Documents, Evaluations and Guide; no model calls or uploads.');
})().catch(e=>{console.error(e);process.exit(1)});
